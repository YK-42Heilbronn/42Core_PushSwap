#include "../push_swap.h"

int	ft_is_space(char c)
{
	if (c == ' ' || c == '\t' || c == '\f' || c == '\v' || c == '\r'
		|| c == '\n')
		return (1);
	return (0);
}

int	ft_isoperator(char c)
{
	if (c == '+' || c == '-')
		return (1);
	return (0);
}
